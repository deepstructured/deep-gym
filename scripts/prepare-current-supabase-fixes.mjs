/** Generate a reviewable SQL Editor script; never connects to any database. */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
const files = ["0010_home_dashboard_summary.sql", "0011_workout_draft_sync.sql", "0012_ensure_current_profile.sql"];
const root = new URL("../", import.meta.url);
const atomic = await readFile(new URL("supabase/migrations/0009_atomic_workout_write.sql",root),"utf8");
const body = atomic.match(/set search_path = ''\nas \$\$([\s\S]*?)\$\$;/)?.[1];
if (!body) throw new Error("Cannot identify the existing atomic function body");
const expected = createHash("md5").update(body).digest("hex");
let sql = `-- Generated by scripts/prepare-current-supabase-fixes.mjs; REVIEW before applying.
-- Target: existing hosted Supabase, migrations 0001-0009 already present.
-- Production catalog was inspected READ ONLY on 2026-11-11: existing 0009 body
-- matches the local source. No 0009 table/index DDL is replayed here.
-- Apply in Supabase SQL Editor as the migration owner BEFORE deploying web code.
-- No application rows are inserted/updated/deleted by this script. 0012 repairs
-- a missing profile only when that authenticated user later calls its RPC.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $preflight$
begin
  if to_regprocedure('public.save_workout_atomic(jsonb,uuid,uuid)') is null then
    raise exception 'Required existing migration 0009 is missing';
  end if;
  if (select md5(prosrc) from pg_proc where oid='public.save_workout_atomic(jsonb,uuid,uuid)'::regprocedure) <> '${expected}' then
    raise exception 'Existing atomic function differs from reviewed migration 0009; stop and review';
  end if;
  if not exists (select 1 from pg_index where indexrelid=to_regclass('public.workouts_user_create_key_idx') and indisvalid and indisunique) then
    raise exception 'Required valid workout idempotency index is missing';
  end if;
  if exists (
    select 1 from (values ('workouts'),('workout_exercises'),('sets'),('exercises'),('workout_drafts'),('profiles')) required(name)
    left join pg_class c on c.oid=to_regclass('public.'||required.name)
    where c.oid is null or not c.relrowsecurity
  ) then raise exception 'Required application tables/RLS are missing'; end if;
  if not has_function_privilege('authenticated','public.save_workout_atomic(jsonb,uuid,uuid)','EXECUTE') then
    raise exception 'Authenticated role cannot execute the existing atomic write';
  end if;
end;
$preflight$;

-- Supabase default privileges can include an explicit anon grant independent
-- of PUBLIC. The atomic function already rejects missing auth.uid(). Tighten
-- its grant without modifying the function, data, columns, index, or policies.
revoke all on function public.save_workout_atomic(jsonb,uuid,uuid) from public, anon;
`;
for (const file of files) {
  const source = await readFile(new URL(`supabase/migrations/${file}`,root),"utf8");
  const hash = createHash("sha256").update(source).digest("hex");
  sql += `\n-- SOURCE ${file}; SHA256 ${hash}\n${source}\n`;
}
sql += `
do $verify$
declare signature text;
begin
  foreach signature in array array[
    'public.save_workout_atomic(jsonb,uuid,uuid)',
    'public.home_dashboard_summary(date,date,date)',
    'public.save_workout_draft(uuid,jsonb,timestamptz)',
    'public.ensure_current_profile()'
  ] loop
    if not has_function_privilege('authenticated',signature,'EXECUTE')
      or has_function_privilege('anon',signature,'EXECUTE') then
      raise exception 'Unexpected RPC permission for %',signature;
    end if;
  end loop;
end;
$verify$;
-- Delivered only after COMMIT, so PostgREST sees all new RPC signatures together.
notify pgrst, 'reload schema';
commit;
`;
const output = new URL("supabase/deploy/2026-11-11_current_runtime_fixes.sql",root);
await mkdir(new URL("supabase/deploy/",root),{recursive:true});
await writeFile(output,sql);
console.log(`Prepared ${output.pathname} (no database connection)`);
